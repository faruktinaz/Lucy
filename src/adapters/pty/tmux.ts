/**
 * Session persistence through a private tmux server (docs/dev/PTY_NOTES.md §13).
 *
 * Each persistent terminal or agent session is one tmux session on a server of Lucy's own
 * (`-L <socket name>`, never the user's default server), started with a configuration file
 * Lucy writes and passes with `-f`, so `~/.tmux.conf` is never read. Lucy's PTY runs only the
 * tmux client: killing the client (quit, crash) detaches and the session keeps running; ending
 * a session in the UI kills the tmux session.
 *
 * The configuration makes tmux transparent; every line was verified with real tmux 3.7b
 * (spikes/pty/21-tmux-config.ts, 22-tmux-wheel.ts).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { constants } from "node:os";
import { dirname } from "node:path";
import { errorMessage } from "@/core/errors";
import { type Disposable, Emitter } from "@/core/events";
import { log } from "@/core/log";
import { run } from "@/core/process";
import { buildPtyEnv } from "./pty-env";
import type { PtyExitInfo, PtyKillOptions, PtyProcess, PtySpawnOptions } from "./pty-process";

const logger = log.child("tmux");

/** extended-keys, allow-passthrough and `run-shell -C` need 3.3. */
export const TMUX_MIN_VERSION = { major: 3, minor: 3 } as const;

export type TmuxAvailability =
  | { readonly ok: true; readonly executable: string; readonly version: string }
  | { readonly ok: false; readonly reason: "missing" | "old" | "broken"; readonly version?: string };

/** `tmux 3.7b` -> 3.7; `tmux next-3.8` -> 3.8; unknown formats -> null. */
export function parseTmuxVersion(text: string): { major: number; minor: number } | null {
  const match = /(\d+)\.(\d+)/.exec(text);
  return match ? { major: Number(match[1]), minor: Number(match[2]) } : null;
}

/** Synchronous (a few milliseconds): runs `tmux -V` once. */
export function detectTmux(env: Record<string, string | undefined> = process.env): TmuxAvailability {
  const executable = Bun.which("tmux", { PATH: env.PATH ?? "" });
  if (!executable) return { ok: false, reason: "missing" };
  try {
    const result = Bun.spawnSync([executable, "-V"], {
      env: { ...process.env, ...env },
      stdout: "pipe",
      stderr: "ignore",
      timeout: 3000,
    });
    const version = result.stdout.toString().trim();
    const parsed = parseTmuxVersion(version);
    if (result.exitCode !== 0 || !parsed) return { ok: false, reason: "broken", version };
    const recent =
      parsed.major > TMUX_MIN_VERSION.major ||
      (parsed.major === TMUX_MIN_VERSION.major && parsed.minor >= TMUX_MIN_VERSION.minor);
    return recent ? { ok: true, executable, version } : { ok: false, reason: "old", version };
  } catch {
    return { ok: false, reason: "broken" };
  }
}

/**
 * The private configuration. Each setting makes tmux invisible or passes something through.
 * Sourced again on every Lucy start, so a running server picks up changes after an update.
 */
export function tmuxConfig(): string {
  return `# Generated by Lucy for its private tmux server. Do not edit; Lucy rewrites it.
# Never read: ~/.tmux.conf. This server is separate from your own tmux.

# Input: no prefix and no key bindings, so every key reaches the program; no Escape delay.
set -g prefix None
set -g prefix2 None
unbind -a -T prefix
unbind -a -T root
set -s escape-time 0

# Modified keys (Shift+Enter, Ctrl+letters) for programs that request them (modifyOtherKeys),
# delivered as CSI u. Focus reports and bracketed paste pass through.
set -s extended-keys on
set -s extended-keys-format csi-u
set -s focus-events on

# Terminal features of Lucy's emulator: truecolor, extended keys, focus, OSC 52 clipboard,
# titles, synchronized output, styled underlines. No alternate screen for the client.
set -s default-terminal "xterm-256color"
set -as terminal-features ",xterm-256color:RGB:extkeys:focus:clipboard:title:sync:usstyle"
set -as terminal-overrides ",xterm-256color:smcup@:rmcup@"
set -s set-clipboard on
set -g allow-passthrough on

# Invisible: no status line; the program's title becomes the terminal's title; bells pass on.
set -g status off
set -g set-titles on
# tmux's default pane title is the host name: forward a title only when the program set one.
set -g set-titles-string "#{?#{||:#{==:#{pane_title},#{host}},#{==:#{pane_title},#{host_short}}},,#{pane_title}}"
set -g bell-action any
set -g visual-bell off
set -g monitor-bell on
set -g window-size latest

# History: kept by tmux, so it survives Lucy restarts. The wheel scrolls it (copy mode, left
# again by scrolling down, q or Escape); programs that track the mouse get mouse events.
set -g history-limit 100000
set -g mouse on
bind -n WheelUpPane if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" "send -M" "copy-mode -e"
bind -n WheelDownPane if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" "send -M"
bind -n MouseDown1Pane if -F "#{mouse_any_flag}" "send -M"
bind -n MouseUp1Pane if -F "#{mouse_any_flag}" "send -M"
bind -n MouseDrag1Pane if -F "#{||:#{pane_in_mode},#{mouse_any_flag}}" "send -M" "copy-mode -M"

# When the program ends, keep the pane (and its exit status) and detach the client, so Lucy
# sees the end, reads the status and shows it.
set -g remain-on-exit on
set-hook -g pane-died "run-shell -C \\"detach-client -s '#{session_name}'\\""
`;
}

export interface TmuxSessionInfo {
  readonly name: string;
  readonly dead: boolean;
  readonly exit: PtyExitInfo | null;
  readonly currentPath: string | null;
  /** Lucy's `@lucy-*` session options (kind, title, order, ...), without the prefix. */
  readonly meta: Readonly<Record<string, string>>;
}

export interface TmuxSessionSpec {
  /** tmux session name. */
  readonly name: string;
  /** The program to run when the session does not exist yet. */
  readonly argv: readonly string[];
  readonly cwd: string;
  /** Stored as `@lucy-<key>` session options (kind, title, order, ...). */
  readonly meta?: Readonly<Record<string, string>>;
}

export interface TmuxBackendOptions {
  executable: string;
  socketName: string;
  configPath: string;
  /** How the client PTY is started; pass `registry.spawn` so quitting kills the client. */
  spawn: (options: PtySpawnOptions) => PtyProcess;
}

/**
 * Variables passed to each new session with `-e`. The server already has Lucy's whole
 * environment (inherited from the client that started it); only values that may differ since
 * then are passed, and never everything: command lines are visible to other processes, and
 * the environment holds tokens.
 */
const FORWARDED_ENV = ["PATH", "COLORTERM", "LANG", "LC_ALL", "LC_CTYPE", "SHELL", "HOME", "USER"];
const META_FORMAT = "@lucy-";
const LIST_FORMAT = [
  "#{session_name}",
  "#{pane_dead}",
  "#{pane_dead_status}",
  "#{pane_dead_signal}",
  "#{pane_current_path}",
].join("\t");

export class TmuxBackend {
  constructor(readonly options: TmuxBackendOptions) {}

  /** `tmux -L <socket> -f <config> ...args` */
  argv(...args: string[]): string[] {
    return [this.options.executable, "-L", this.options.socketName, "-f", this.options.configPath, ...args];
  }

  /** Writes the configuration and applies it to a server that is already running. */
  async prepare(): Promise<void> {
    mkdirSync(dirname(this.options.configPath), { recursive: true });
    writeFileSync(this.options.configPath, tmuxConfig(), { mode: 0o600 });
    // No server yet is fine: the first client starts one with -f.
    await run(this.argv("source-file", this.options.configPath), { timeoutMs: 3000 }).catch(() => undefined);
  }

  /**
   * A spawner that attaches to the session, creating it first when it does not exist. A
   * session whose program already ended is replaced, so Restart starts over.
   */
  spawner(spec: TmuxSessionSpec): (options: PtySpawnOptions) => PtyProcess {
    return (options) => {
      if (this.paneDeadSync(spec.name)) this.run(["kill-session", "-t", spec.name]);
      const env = buildPtyEnv({ overrides: options.env });
      // Explicit overrides (a shell's PS1 in tests, TERM_PROGRAM_VERSION) are intentional.
      const names = new Set([...FORWARDED_ENV, ...Object.keys(options.env ?? {})]);
      names.delete("TERM_PROGRAM");
      const envFlags = [...names]
        .filter((key) => env[key] !== undefined)
        .flatMap((key) => ["-e", `${key}=${env[key]}`]);
      // A lone ";" separates tmux commands; escape one inside the program's arguments.
      const program = spec.argv.map((arg) => (arg === ";" ? "\\;" : arg));
      const meta = Object.entries(spec.meta ?? {}).flatMap(([key, value]) => [
        ";",
        "set-option",
        "-q",
        "-t",
        spec.name,
        `${META_FORMAT}${key}`,
        value,
      ]);
      const client = this.options.spawn({
        ...options,
        argv: this.argv(
          "new-session",
          "-A",
          "-s",
          spec.name,
          "-c",
          spec.cwd,
          ...envFlags,
          "--",
          ...program,
          ...meta,
        ),
        cwd: spec.cwd,
      });
      return new TmuxPty(client, this, spec.name);
    };
  }

  /** Sessions whose name starts with `prefix`, with their state and Lucy metadata. */
  async list(prefix: string): Promise<TmuxSessionInfo[]> {
    const result = await run(this.argv("list-panes", "-a", "-F", LIST_FORMAT), { timeoutMs: 3000 }).catch(
      () => null,
    );
    if (result?.code !== 0) return []; // no server: no sessions
    const sessions: TmuxSessionInfo[] = [];
    for (const line of result.stdout.split("\n")) {
      const [name, dead, status, signal, path] = line.split("\t");
      if (!name?.startsWith(prefix) || sessions.some((session) => session.name === name)) continue;
      const isDead = dead === "1";
      sessions.push({
        name,
        dead: isDead,
        exit: isDead ? exitFrom(status, signal) : null,
        currentPath: path || null,
        meta: await this.meta(name),
      });
    }
    return sessions;
  }

  private async meta(name: string): Promise<Record<string, string>> {
    const result = await run(this.argv("show-options", "-q", "-t", name), { timeoutMs: 3000 }).catch(
      () => null,
    );
    const out: Record<string, string> = {};
    for (const line of result?.stdout.split("\n") ?? []) {
      if (!line.startsWith(META_FORMAT)) continue;
      const space = line.indexOf(" ");
      if (space < 0) continue;
      out[line.slice(META_FORMAT.length, space)] = unquote(line.slice(space + 1));
    }
    return out;
  }

  async setMeta(name: string, meta: Readonly<Record<string, string>>): Promise<void> {
    for (const [key, value] of Object.entries(meta)) {
      await run(this.argv("set-option", "-q", "-t", name, `${META_FORMAT}${key}`, value), {
        timeoutMs: 3000,
      }).catch(() => undefined);
    }
  }

  /** How the session's program ended, or null while it runs (or when the session is gone). */
  async exitInfo(name: string): Promise<{ state: "running" | "dead" | "missing"; exit: PtyExitInfo | null }> {
    const result = await run(
      this.argv(
        "display-message",
        "-p",
        "-t",
        name,
        "#{pane_dead}\t#{pane_dead_status}\t#{pane_dead_signal}",
      ),
      { timeoutMs: 3000 },
    ).catch(() => null);
    if (result?.code !== 0) return { state: "missing", exit: null };
    const [dead, status, signal] = result.stdout.trim().split("\t");
    return dead === "1"
      ? { state: "dead", exit: exitFrom(status, signal) }
      : { state: "running", exit: null };
  }

  async killSession(name: string): Promise<void> {
    await run(this.argv("kill-session", "-t", name), { timeoutMs: 3000 }).catch((error: unknown) => {
      logger.warn("kill-session failed", { error: errorMessage(error) });
    });
  }

  /** Ends every session whose name starts with `prefix`; returns how many were ended. */
  async killSessions(prefix: string): Promise<number> {
    const sessions = await this.list(prefix);
    for (const session of sessions) await this.killSession(session.name);
    return sessions.length;
  }

  private paneDeadSync(name: string): boolean {
    return this.run(["display-message", "-p", "-t", name, "#{pane_dead}"]).trim() === "1";
  }

  private run(args: string[]): string {
    try {
      // An explicit env: Bun.spawnSync does not see later changes to process.env (TMUX_TMPDIR).
      const result = Bun.spawnSync(this.argv(...args), {
        env: { ...process.env },
        stdout: "pipe",
        stderr: "ignore",
        timeout: 3000,
      });
      return result.exitCode === 0 ? result.stdout.toString() : "";
    } catch {
      return "";
    }
  }
}

function exitFrom(status: string | undefined, signal: string | undefined): PtyExitInfo {
  const code = Number.parseInt(status ?? "", 10);
  const signalNumber = Number.parseInt(signal ?? "", 10);
  if (Number.isFinite(signalNumber) && signalNumber > 0) {
    const name = Object.entries(constants.signals as Record<string, number>).find(
      ([, value]) => value === signalNumber,
    )?.[0];
    return { code: null, signal: name ?? `signal ${signalNumber}` };
  }
  return { code: Number.isFinite(code) ? code : null, signal: null };
}

function unquote(value: string): string {
  const trimmed = value.trim();
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1).replace(/\\(.)/g, "$1");
  }
  return trimmed;
}

/**
 * The tmux client in Lucy's PTY, seen as the session itself: output and input go through the
 * client; `kill()` ends the tmux session; dispose, hangup and killSync only detach. When the
 * client exits, the session is asked how its program ended.
 */
class TmuxPty implements PtyProcess {
  readonly exited: Promise<PtyExitInfo>;
  private readonly exitEmitter = new Emitter<PtyExitInfo>();
  private ending = false;
  private info: PtyExitInfo | null = null;

  constructor(
    private readonly client: PtyProcess,
    private readonly backend: TmuxBackend,
    readonly name: string,
  ) {
    this.exited = client.exited.then(async (clientInfo) => {
      let info = clientInfo;
      if (this.ending) info = { code: null, signal: "SIGHUP" };
      else {
        const state = await this.backend.exitInfo(name);
        // Detached while the program still runs (Lucy quitting): report the client's exit.
        if (state.state === "dead" && state.exit) info = state.exit;
        else if (state.state === "missing") info = { code: null, signal: "SIGHUP" };
      }
      this.info = info;
      this.exitEmitter.emit(info);
      this.exitEmitter.dispose();
      return info;
    });
  }

  get pid(): number {
    return this.client.pid;
  }
  get argv(): readonly string[] {
    return this.client.argv;
  }
  get cols(): number {
    return this.client.cols;
  }
  get rows(): number {
    return this.client.rows;
  }
  get isRunning(): boolean {
    return this.client.isRunning;
  }
  get exitInfo(): PtyExitInfo | null {
    return this.info;
  }

  write(data: string | Uint8Array): boolean {
    return this.client.write(data);
  }

  resize(cols: number, rows: number): void {
    this.client.resize(cols, rows);
  }

  /** Ends the tmux session (the program and everything it started), then the client exits. */
  kill(_options?: PtyKillOptions): Promise<PtyExitInfo> {
    if (!this.ending) {
      this.ending = true;
      void this.backend.killSession(this.name).finally(() => {
        // The client normally exits by itself once its session is gone.
        if (this.client.isRunning) void this.client.kill();
      });
    }
    return this.exited;
  }

  /** Detaches (shutdown path): the session keeps running. */
  killSync(options?: PtyKillOptions): void {
    this.client.killSync(options);
  }

  hangup(): void {
    this.client.hangup();
  }

  onData(listener: (data: Uint8Array) => void): Disposable {
    return this.client.onData(listener);
  }

  onExit(listener: (info: PtyExitInfo) => void): Disposable {
    return this.exitEmitter.on(listener);
  }

  /** Detaches: the client goes away, the session stays (unless `kill()` was called). */
  dispose(): void {
    this.client.dispose();
  }
}
