/** Identifier start not preceded by a word character or a colon (keeps `Foo::Bar` intact). */
const SYMBOL = /(?<![:\p{L}\p{N}_]):(?:[\p{L}_][\p{L}\p{N}_]*[?!=]?|"(?:[^"\\\n]|\\.)*")/uy;

